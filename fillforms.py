bad, tot, plain = [], 0, 0
for f in sorted(glob.glob("*.json")):
    if f in ("lv13.json", "lv23.json"): continue
    J = json.load(io.open(f, encoding="utf-8"))
    for it in J["items"]:
        forms = it.get("forms") or []
        table = FILL.get(it["id"], {})
        out = []
        for x in forms:
            if "~" not in x:
                out.append([[x, R]]); plain += 1; continue
            parts = table.get(x)
            if not parts:
                bad.append((it["id"], x)); out.append([[x, R]]); continue
            joined = "".join(t for t, _ in parts)
            if "~" in joined: bad.append((it["id"], x + "  ← 채운 것에 ~ 가 남음"))
            if not any(c == B for _, c in parts): bad.append((it["id"], x + "  ← 검은 자리 없음"))
            out.append([[t, c] for t, c in parts]); tot += 1
        it["forms_filled"] = out
    io.open(f, "w", encoding="utf-8").write(json.dumps(J, ensure_ascii=False, indent=1))

print(f"  채운 문형 {tot}개 · 채울 것 없는 문형 {plain}개")
